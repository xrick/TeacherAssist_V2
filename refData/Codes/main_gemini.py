@app.post("/generate")
async def generate_ppt_endpoint(request: TopicRequest):
    """API 端點：接收主題 -> 生成 -> 回傳檔案"""

    # 1. 取得 AI 文字內容
    ppt_data = get_llm_content(request.topic)

    # 2. 轉換為 PPT 二進位流
    ppt_stream = generate_pptx_binary(ppt_data)

    # 3. 回傳串流 (瀏覽器會視為檔案下載)
    filename = f"AI_Gen_{request.topic}.pptx"
    # 使用 quote 處理中文檔名 (雖然現代瀏覽器通常很聰明，但最好標準化)
    from urllib.parse import quote
    filename_encoded = quote(filename)

    return StreamingResponse(
        ppt_stream,
        media_type="application/vnd.openxmlformats-officedocument.presentationml.presentation",
        headers={
            "Content-Disposition": f"attachment; filename*=UTF-8''{filename_encoded}"
        }
    )


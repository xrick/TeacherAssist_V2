def get_llm_content(topic: str):
    """呼叫 LLM 取得 JSON 結構"""
    print(f"[Backend] 正在分析主題: {topic}")
    system_prompt = """
    你是一個專業簡報設計師。請根據主題生成 JSON 格式的簡報大綱 (繁體中文)。
    JSON 結構必須包含：
    {
        "title": "大標題",
        "slides": [
            {
                "title": "頁面標題",
                "content": ["重點1", "重點2"],
                "image_query": "英文圖片搜尋關鍵字"
            }
        ]
    }
    請只回傳 JSON，不要包含 Markdown 格式。
    """

    try:
        response = client.chat.completions.create(
            model=MODEL_NAME,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": f"主題：{topic}。請製作 3 頁簡報。"},
            ],
            temperature=0.7,
        )
        content = response.choices[0].message.content
        # 清理字串，確保 JSON 可解析
        content = content.replace("```json", "").replace("```", "").strip()
        return json.loads(content)
    except Exception as e:
        print(f"[Error] LLM 處理失敗: {e}")
        raise HTTPException(status_code=500, detail="LLM 生成失敗，請檢查 Ollama 是否開啟。")

def download_image_stream(keyword: str):
    """下載圖片並回傳 BytesIO 物件"""
    try:
        # 使用 Lorem Picsum 模擬圖片搜尋
        # 在正式版請換成 Unsplash API
        url = f"https://picsum.photos/800/600?random={hash(keyword)}"
        res = requests.get(url, timeout=5)
        if res.status_code == 200:
            return io.BytesIO(res.content)
    except Exception as e:
        print(f"[Warning] 圖片下載失敗 ({keyword}): {e}")
    return None

def generate_pptx_binary(data: dict) -> io.BytesIO:
    """在記憶體中生成 PPT 並回傳 Binary Stream"""
    prs = Presentation()

    # 1. 封面
    slide = prs.slides.add_slide(prs.slide_layouts[0])
    slide.shapes.title.text = data.get("title", "AI Presentation")
    slide.placeholders[1].text = "Generated by FastAPI & Python-pptx"

    # 2. 內容頁
    bullet_layout = prs.slide_layouts[1]

    for slide_data in data.get("slides", []):
        slide = prs.slides.add_slide(bullet_layout)
        shapes = slide.shapes

        # 標題
        shapes.title.text = slide_data.get("title", "")

        # 調整文字框 (左半邊)
        body_shape = shapes.placeholders[1]
        body_shape.width = Inches(5.0)
        body_shape.left = Inches(0.5)

        tf = body_shape.text_frame
        tf.word_wrap = True
        for point in slide_data.get("content", []):
            p = tf.add_paragraph()
            p.text = point
            p.level = 0

        # 插入圖片 (右半邊)
        img_query = slide_data.get("image_query")
        if img_query:
            img_stream = download_image_stream(img_query)
            if img_stream:
                try:
                    shapes.add_picture(
                        img_stream,
                        left=Inches(5.8),
                        top=Inches(2.0),
                        height=Inches(3.5)
                    )
                except Exception as e:
                    print(f"[Error] 插入圖片失敗: {e}")

    # 關鍵：儲存到 BytesIO 而不是磁碟
    output = io.BytesIO()
    prs.save(output)
    output.seek(0) # 指標歸零，準備讀取
    return output


app = FastAPI(title="AI PPT Generator")

# 設定 LLM (請確保您的 Ollama 正在運行)
client = OpenAI(
    base_url="http://localhost:11434/v1",
    api_key="ollama",
)
MODEL_NAME = "gpt-oss:20b"  # 或您本地實際的模型名稱

# 定義請求資料模型
class TopicRequest(BaseModel):
    topic: str

